-- Least-privilege application group for PostgreSQL row-level security.
--
-- This is provisioning, not a schema migration, because roles are cluster
-- objects and a login credential is deployment configuration. Run it as the
-- table owner after applying infra/migrations/010_row_level_security.sql.
--
-- The role created here is NOLOGIN: it carries privileges only. A deployment
-- creates a separate login role, grants this group to it, and points the
-- application connection string (for example the Hyperdrive binding) at that
-- login. The login role must be:
--
--   * NOSUPERUSER
--   * NOBYPASSRLS
--   * not the owner of any of these tables
--
-- See infra/database/README.md for the exact activation steps.
--
-- The grants are exactly the operations the API performs:
--
--   catalog_products       select, insert, update   (no delete)
--   catalog_versions       select, insert           (immutable history)
--   media_attachments      select, insert, update   (no delete)
--   ai_jobs                select, insert, update   (no delete)
--   ai_proposals           select, insert, update   (no delete)
--   inquiries              select, insert           (no update/delete yet)
--   identity_*             see below                (no RLS in this slice)
--
-- There are no sequences to grant: every id is application-supplied or
-- generated by a built-in function, not a sequence.

do $$
begin
  if not exists (
    select 1
    from pg_roles
    where rolname = 'artisan_marketplace_app'
  ) then
    create role artisan_marketplace_app
      nologin
      nosuperuser
      nobypassrls
      nocreatedb
      nocreaterole
      inherit;
  end if;
end
$$;

comment on role artisan_marketplace_app is
  'NOLOGIN privilege group for the Artisan Marketplace API. A deployment grants this group to a non-owner, NOBYPASSRLS login role.';

-- Schema access.
grant usage on schema public to artisan_marketplace_app;
grant usage on schema app to artisan_marketplace_app;

-- The narrow published projection discovery may read.
grant select on app.published_catalog_products
  to artisan_marketplace_app;

-- The actor helper is invoked while policies are evaluated.
grant execute on function app.current_actor_id()
  to artisan_marketplace_app;

-- Owner-scoped catalog and AI data.
grant select, insert, update
  on public.catalog_products
  to artisan_marketplace_app;

grant select, insert
  on public.catalog_versions
  to artisan_marketplace_app;

grant select, insert, update
  on public.media_attachments
  to artisan_marketplace_app;

grant select, insert, update
  on public.ai_jobs
  to artisan_marketplace_app;

grant select, insert, update
  on public.ai_proposals
  to artisan_marketplace_app;

-- Outbox events: dispatcher claims (update), publishes, acknowledges (update)
-- or releases (update). Consumer reads (select) not needed but harmless.
grant select, insert, update
  on public.ai_job_outbox
  to artisan_marketplace_app;

grant select, insert
  on public.inquiries
  to artisan_marketplace_app;

-- Identity is intentionally outside RLS in this slice: it is read and written
-- before an actor identity exists. The grants stay least-privilege so the
-- application can perform exactly the operations its session store performs.
grant select, insert
  on public.identity_accounts
  to artisan_marketplace_app;

grant select, insert, update
  on public.identity_sessions
  to artisan_marketplace_app;

grant select, insert, update
  on public.identity_refresh_grants
  to artisan_marketplace_app;
